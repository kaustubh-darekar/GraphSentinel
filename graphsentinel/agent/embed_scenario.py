"""Pre-compute OpenAI embeddings into a scenario file, so scripted replays need no key.

    python -m graphsentinel.agent.embed_scenario 05_paraphrased_leak

Replays the scenario once with the OpenAI embedder, records every vector it asked for,
and writes them to an `embeddings:` block at the end of the YAML file.
"""

from __future__ import annotations

import argparse
import os
import re
from pathlib import Path

from dotenv import load_dotenv

from graphsentinel.agent.embedders import OpenAIEmbedder, openai_embedder_available
from graphsentinel.agent.runner_scripted import SCENARIO_DIR, find_scenario, run_scenario
from graphsentinel.core.config import Settings
from graphsentinel.core.embedding import clip, text_key
from graphsentinel.core.sentinel import Sentinel


class RecordingEmbedder:
    """Wraps an embedder and keeps every vector it produced, keyed by text."""

    def __init__(self, inner: OpenAIEmbedder) -> None:
        self.inner = inner
        self.name = inner.name
        self.threshold = inner.threshold
        self.vectors: dict[str, list[float]] = {}

    @property
    def dims(self) -> int:
        """Vector size of the wrapped embedder."""
        return self.inner.dims

    def embed(self, texts: list[str]) -> list[list[float]]:
        """Embed and remember."""
        vecs = self.inner.embed(texts)
        for t, v in zip(texts, vecs):
            self.vectors[text_key(clip(t))] = [round(x, 6) for x in v]
        return vecs


def write_block(path: Path, model: str, dims: int, threshold: float,
                vectors: dict[str, list[float]]) -> None:
    """Replace the file's trailing `embeddings:` block (if any) with a new one."""
    text = path.read_text(encoding="utf-8")
    text = re.split(r"\n# --- pre-computed embeddings", text)[0].rstrip() + "\n"
    lines = ["", "# --- pre-computed embeddings (generated by graphsentinel.agent.embed_scenario;",
             "# scripted mode replays these so no API key is needed)",
             "embeddings:", f"  model: {model}", f"  dims: {dims}", f"  threshold: {threshold}",
             "  vectors:"]
    # Fixed-point floats: YAML 1.1 reads exponent forms like 1e-06 as strings.
    lines += [f"    {k}: [{', '.join(f'{x:.6f}' for x in v)}]" for k, v in sorted(vectors.items())]
    path.write_text(text + "\n".join(lines) + "\n", encoding="utf-8")


def main() -> int:
    """Entry point."""
    load_dotenv()
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("scenario")
    args = ap.parse_args()
    if not openai_embedder_available():
        print("Set OPENAI_API_KEY and OPENAI_EMBED_MODEL in .env first.")
        return 2
    sc = find_scenario(args.scenario)
    path = SCENARIO_DIR / f"{sc.id}.yaml"
    rec = RecordingEmbedder(OpenAIEmbedder(os.environ["OPENAI_EMBED_MODEL"]))
    sentinel = Sentinel.open(Settings(store_path=":memory:"))
    try:
        result = run_scenario(sentinel, sc, lineage="precise", embedder=rec)
    finally:
        sentinel.close()
    write_block(path, rec.inner.model, rec.dims, rec.threshold, rec.vectors)
    verdicts = ", ".join(f"step {c.step}: {c.actual}" for c in result.checks)
    print(f"Wrote {len(rec.vectors)} vectors ({rec.dims} dims, {rec.inner.model}) to {path.name}; {verdicts}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
